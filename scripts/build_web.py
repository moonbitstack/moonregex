"""Build the library for the browser and drop it next to the site.

The showcase's playground calls the real engine, not a JavaScript
re-implementation of it: `src/examples/browser` is a tiny package whose `main`
publishes one
function on `globalThis`, and the page calls that. This script builds it for
the `js` backend and copies the single emitted file into `docs/assets/`.

    python scripts/build_web.py

The output is not committed: the docs workflow builds it before publishing.
"""

import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "assets" / "moonregex_web.js"
ARTIFACT = ROOT / "_build" / "js" / "release" / "build" / "examples" / "browser" / "browser.js"

BANNER = """// moonregex, compiled to JavaScript for the showcase page.
//
// Generated by scripts/build_web.py from src/examples/browser — do not edit by hand.
// The entry point is globalThis.moonregexWeb.run(pattern, flags, text, mode),
// which answers a JSON string; see src/examples/browser/web.mbt for the shape.
"""


def main() -> int:
    build = subprocess.run(
        ["moon", "build", "src/examples/browser", "--target", "js", "--release"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    if build.returncode != 0:
        sys.stderr.write(build.stdout + build.stderr)
        return build.returncode
    if not ARTIFACT.exists():
        sys.stderr.write(f"no artifact at {ARTIFACT}\n")
        return 1
    body = ARTIFACT.read_text(encoding="utf-8")
    OUT.write_text(BANNER + body, encoding="utf-8", newline="\n")
    size = OUT.stat().st_size
    print(f"{OUT.relative_to(ROOT)}  {size / 1_000_000:.2f} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
