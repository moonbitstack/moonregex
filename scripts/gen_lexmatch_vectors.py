"""Generate the vectors that hold the lexmatch grammar to Python's meaning.

Two things the core library's grammar leaves out are read the Python way here:
the shorthand classes `\\d`, `\\w`, `\\s` and their negations, and named
captures. "The same meaning" is a measurement, so the corpus below is run
through CPython's `re`, and its answers are written out for
`src/lexmatch_vectors_test.mbt` to replay with `dialect=Lexmatch`.

Python has no `(?<name>…)` spelling, so each pattern is held in the lexmatch
spelling here and run through `re` in its `(?P<name>…)` spelling there; the
answers are the same, which is the claim being checked.

Run it with:

    python scripts/gen_lexmatch_vectors.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from gen_vectors import describe, quote, re  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "lexmatch_vectors_test.mbt"

# ---------------------------------------------------------------------------
# The corpus
# ---------------------------------------------------------------------------
#
# Patterns that both grammars accept and that mean the same thing in both. The
# parts where the two grammars deliberately differ — `.` crosses a newline in
# lexmatch, `$` is anchored to the whole text, `\\b` is ASCII — are not here,
# and are covered by their own tests.

CORPUS: list[tuple[str, list[str]]] = [
    # -- the shorthand classes ---------------------------------------------
    ("\\d+", ["a12b34", "no digits"]),
    ("\\d{4}", ["in 2026 ok", "2026"]),
    ("\\D+", ["12ab34", "123"]),
    ("\\w+", ["héllo, 東京", "_x1"]),
    ("\\W+", ["ab, cd!", "abc"]),
    ("\\s+", ["a \t b\u00a0c", "abc"]),
    ("\\S+", [" ab cd ", "   "]),
    # -- and inside a class -------------------------------------------------
    ("[\\d]+", ["a12b", "none"]),
    ("[\\s\\d]+", ["a 1\t2b", "ab"]),
    ("[^\\d]+", ["12ab34", "1234"]),
    ("[a-f\\d]+", ["abc123", "xyz"]),
    ("[\\w.]+", ["ab.cd ef", "  "],),
    # -- named captures -----------------------------------------------------
    ("(?<year>\\d{4})-(?<month>\\d{2})", ["on 2026-10-28", "2026"]),
    ("(?<word>\\w+)\\s(?<num>\\d+)", ["cell 42 and 7", "no number"]),
    ("(?<c>\\d)(?<d>\\d)", ["12", "1"]),
    # -- the two together ---------------------------------------------------
    ("(?<n>\\d+)\\s*\\w+", ["12 apples", "none"]),
    ("\\w+\\s\\d+", ["say 42 times", "42"]),
]


def python_form(pattern: str) -> str:
    """The same pattern in the spelling CPython's `re` reads."""
    return pattern.replace("(?<", "(?P<")


def main() -> int:
    lines: list[str] = []
    for pattern, texts in CORPUS:
        for text in texts:
            line = describe(re, python_form(pattern), 0, "", text)
            if line is None:
                print(f"  skipped: {pattern!r} {text!r}", file=sys.stderr)
                continue
            fields = line.split("\t")
            fields[1] = pattern
            lines.append("\t".join(fields))
    body = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/gen_lexmatch_vectors.py from CPython's `re`.",
        "// Do not edit by hand: run the script again.",
        "",
        "///|",
        "let lexmatch_vectors : Array[String] = [",
    ]
    for line in lines:
        body.append(f'  "{quote(line)}",')
    body.append("]")
    body.append("")
    OUT.write_text("\n".join(body), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(lines)} cases")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
