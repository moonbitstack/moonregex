"""Generate the full-case-folding vectors.

Every code point whose case folding is longer than one character — the `F`
entries of CaseFolding.txt, the ones `ß` to `ss` and `ﬁ` to `fi` come from —
gets at least one vector here, in both directions: the character written in the
pattern against its folded text, and the folded text written in the pattern
against the character.

The corpus is run through the `regex` package and written out as the same
tab-separated data `scripts/gen_vectors.py` produces, so `moon test` replays it
through the same harness.  Run it with:

    python scripts/gen_fullcase_vectors.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "fullcase_vectors_test.mbt"

sys.path.insert(0, str(Path(__file__).resolve().parent))

import gen_vectors  # noqa: E402 - the vector format lives in one place

try:
    import regex as mrab
except ImportError:  # pragma: no cover - the generator needs it
    sys.exit("python -m pip install regex")


def folding_code_points() -> list[int]:
    """The code points whose case folding is longer than one character."""
    return [cp for cp in range(0x110000) if len(chr(cp).casefold()) > 1]


def agrees(pattern: str, text: str, fold: str) -> bool:
    """Whether the reference answers the way canonical caseless matching does.

    A vector pins the two implementations to one another, so a case the two do
    not agree on is not a vector: it is a divergence, and it is written down
    separately. The reference has one, U+0130: it ends a match inside the
    character's own fold, so `(?fi)İ` matches just `i` of `i̇`.
    """
    return (mrab.fullmatch(pattern, text) is not None) == (text.casefold() == fold)


def main() -> int:
    codes = folding_code_points()
    lines: list[str] = []
    pairs: list[tuple[str, str]] = []
    divergences: list[tuple[str, str]] = []

    for cp in codes:
        char = chr(cp)
        fold = char.casefold()
        pairs.append((char, fold))
        # The character in the pattern, its folded text in the subject.
        texts = [fold, fold.upper(), char]
        # The folded text in the pattern, the character in the subject.
        cases = [(f"(?fi){char}", text) for text in texts]
        cases.append((f"(?fi){fold}", char))
        wrote = False
        for pattern, text in cases:
            if not agrees(pattern, text, fold):
                if (char, fold) not in divergences:
                    divergences.append((char, fold))
                continue
            line = gen_vectors.describe(mrab, pattern, 0, "", text)
            if line is not None:
                lines.append(line)
                wrote = True
        if not wrote:
            print(f"  no vector for U+{cp:04X}", file=sys.stderr)

    body = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/gen_fullcase_vectors.py from the `regex` package.",
        "// Do not edit by hand: run the script again.",
        "//",
        f"// {len(codes)} code points fold to more than one character; each has at",
        "// least one vector, and each appears in `fullcase_pairs` beside its fold.",
        "",
        "let fullcase_vectors : Array[String] = [",
    ]
    for line in lines:
        body.append(f'  "{gen_vectors.quote(line)}",')
    body.append("]")
    body.append("")
    body.append("///|")
    body.append("/// Each code point with a fold longer than itself, and that fold.")
    body.append("let fullcase_pairs : Array[(String, String)] = [")
    for char, fold in pairs:
        body.append(
            f'  ("{gen_vectors.quote(gen_vectors.esc(char))}",'
            f' "{gen_vectors.quote(gen_vectors.esc(fold))}"),'
        )
    body.append("]")
    body.append("")
    body.append("///|")
    body.append("/// The code points the reference and canonical caseless matching read")
    body.append("/// differently: no vector pins these, and the README says why.")
    body.append("let fullcase_divergences : Array[(String, String)] = [")
    for char, fold in divergences:
        body.append(
            f'  ("{gen_vectors.quote(gen_vectors.esc(char))}",'
            f' "{gen_vectors.quote(gen_vectors.esc(fold))}"),'
        )
    body.append("]")
    body.append("")
    OUT.write_text("\n".join(body), encoding="utf-8")
    print(
        f"{OUT.relative_to(ROOT)}: {len(codes)} code points,"
        f" {len(lines)} vectors, {len(divergences)} divergent"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
